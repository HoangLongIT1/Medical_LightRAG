"""
Safety Guardrail Node (Layer 0 — Hard Safety Gate)

This node sits BEFORE everything else in the flow.
It classifies user input as SAFE, WARN, or BLOCK.

- SAFE  → Continue to ClinicalStateManager (normal flow)
- WARN  → Continue BUT flag the conversation for monitoring
- BLOCK → Immediately return safety response, skip ALL medical logic
"""

