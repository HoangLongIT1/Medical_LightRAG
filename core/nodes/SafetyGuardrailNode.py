class SafetyGuardrailNode(Node):
    """
    Layer 0: Hard Safety Gate.

    Classifies user input and either allows it through (SAFE/WARN)
    or blocks it entirely (BLOCK) with a hardcoded safety response.
    """

    def __init__(self, max_retries=1, wait=0):
        super().__init__(max_retries=max_retries, wait=wait)

    def prep(self, shared):
        query = shared.get("input", shared.get("query", ""))
        logger.info(f"🛡️ [SafetyGuardrail] PREP - Checking input: '{query[:80]}...'")
        return {"query": query}

    def exec(self, inputs):
        query = inputs["query"]

        if not query or not query.strip():
            return {"classification": "SAFE", "reason": "Empty input", "threat_type": "none"}

        # Call LLM to classify the input
        prompt = SAFETY_GUARDRAIL_PROMPT.format(user_input=query)

        try:
            response_str = call_llm(prompt, max_retry_time=timeout_config.LLM_RETRY_TIMEOUT)
            result = parse_json_from_llm(response_str)

            if not result or not isinstance(result, dict):
                logger.warning("🛡️ [SafetyGuardrail] EXEC - Could not parse LLM response, defaulting to SAFE")
                return {"classification": "SAFE", "reason": "Parse error", "threat_type": "none"}

            classification = result.get("classification", "SAFE").upper()
            reason = result.get("reason", "")
            threat_type = result.get("threat_type", "none")

            # Validate classification
            if classification not in {"SAFE", "WARN", "BLOCK"}:
                classification = "SAFE"

            logger.info(f"🛡️ [SafetyGuardrail] EXEC - Classification: {classification} | Threat: {threat_type} | Reason: {reason}")
            return {
                "classification": classification,
                "reason": reason,
                "threat_type": threat_type,
            }

        except Exception as e:
            logger.error(f"🛡️ [SafetyGuardrail] EXEC - Error during safety check: {e}")
            # On error, default to SAFE to avoid blocking legitimate queries
            return {"classification": "SAFE", "reason": f"Error: {str(e)}", "threat_type": "none"}

    def post(self, shared, prep_res, exec_res):
        if exec_res is None:
            logger.error("🛡️ [SafetyGuardrail] POST - exec_res is None, allowing through")
            return "safe"

        classification = exec_res.get("classification", "SAFE")
        threat_type = exec_res.get("threat_type", "none")
        reason = exec_res.get("reason", "")

        # Store safety metadata in shared for downstream nodes
        shared["safety_classification"] = classification
        shared["safety_threat_type"] = threat_type
        shared["safety_reason"] = reason

        if classification == "BLOCK":
            # HARD BLOCK: Set the answer directly and skip the entire pipeline
            block_response = BLOCK_RESPONSES.get(threat_type, BLOCK_RESPONSE_DEFAULT)

            shared["answer_obj"] = {
                "explanation": block_response,
                "suggestion_questions": [
                    "Tôi muốn hỏi về triệu chứng bệnh",
                    "Tôi cần tư vấn về thuốc điều trị",
                    "Tôi cần thông tin về chế độ dinh dưỡng",
                ],
            }
            shared["explain"] = block_response
            shared["suggestion_questions"] = shared["answer_obj"]["suggestion_questions"]

            logger.warning(f"🛡️ [SafetyGuardrail] POST - ⛔ BLOCKED: {reason} (threat={threat_type})")
            return "blocked"

        elif classification == "WARN":
            logger.warning(f"🛡️ [SafetyGuardrail] POST - ⚠️ WARN: {reason} (threat={threat_type})")
            return "safe"  # Allow through but logged

        else:
            logger.info(f"🛡️ [SafetyGuardrail] POST - ✅ SAFE: {reason}")
            return "safe"
